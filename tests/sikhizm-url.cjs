const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), ts = require('typescript');
require.extensions['.ts'] = (module, filename) => {
  const source = fs.readFileSync(filename, 'utf8').replace(/(["'])@\/([^"']+)\1/g, (_, quote, file) => JSON.stringify(path.join(__dirname, '../src', file)));
  module._compile(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, esModuleInterop: true } }).outputText, filename);
};
const { POST } = require('../src/app/api/hukamnama/sikhizm/route.ts');
const { parseSikhizmArticleContent, parseSikhizmLiveArticle } = require('../src/lib/hukamnama/liveSource.ts');
const { loadedContent } = require('../src/lib/hukamnama/loadedContent.ts');
const { verifyFreshMorningState } = require('../src/lib/morningPlan.ts');
const { defaultState } = require('../src/lib/hukamnama/defaults.ts');
const html = fs.readFileSync('tests/fixtures/sikhizm-2026-10-28.html', 'utf8');
const content = parseSikhizmArticleContent(html);
const url = 'https://sikhizm.com/man-re-prabh-ki-saran-bichaaro/';
const request = body => new Request('https://app.example/api/hukamnama/sikhizm', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(body) });
const page = (text = html) => new Response(text, { headers: { 'Content-Type': 'text/html; charset=UTF-8' } });
const realDate = Date, realFetch = fetch;
class FixedDate extends realDate { constructor(value) { super(value === undefined ? '2026-10-29T00:30:00Z' : value); } }
(async () => {
  global.Date = FixedDate;
  let calls = [];
  global.fetch = async (url, options) => { calls.push([String(url), options]); return page(); };
  const response = await POST(request({ url, translation: false }));
  assert.equal(response.status, 200);
  assert.equal(response.headers.get('cache-control'), 'no-store');
  const record = await response.json();
  assert.equal(record.sourceDateISO, '2026-10-29');
  assert.ok(record.dateText.startsWith('29-October-2026'));
  assert.equal(record.isToday, false); assert.equal(record.manualUrl, url);
  assert.equal(record.original, content.original); assert.equal(record.translation, content.translation);
  assert.equal(record.ang, '632'); assert.equal(record.matchedAuthor, 'Guru Tegh Bahadur Ji');
  assert.equal(calls.length, 1); assert.equal(calls[0][1].cache, 'no-store');
  assert.equal(calls[0][1].redirect, 'manual');
  const applied = loadedContent(record);
  assert.ok(applied.original.endsWith('॥੧॥'));
  const state = { ...defaultState(), ...applied, dateISO: record.sourceDateISO, dateText: record.dateText, ang: record.ang, banikar: record.matchedAuthor };
  assert.equal(verifyFreshMorningState(state, record).matchesLive, false);
  assert.equal(verifyFreshMorningState(state, { ...record, isToday: true }).matchesLive, false, 'manual imports never qualify for auto-post');
  assert.throws(() => parseSikhizmLiveArticle(html, { publishedAt: '2026-10-28T00:00:45Z', localDateISO: '2026-10-28' }, '2026-10-29'), /not confirmed for today/);
  for (const bad of ['http://sikhizm.com/post/', 'https://other.example/post/', 'https://sikhizm.com.evil.example/', 'https://127.0.0.1/', 'https://user:secret@sikhizm.com/post/', 'https://sikhizm.com:444/post/', 'https://sikhizm.com/wp-admin/']) {
    calls = [];
    const result = await POST(request({ url: bad }));
    assert.equal(result.status, 400, bad); assert.equal(calls.length, 0, 'reject before any network request');
  }
  for (const body of [null, {}, { url: ' ' }, { url, translation: 'yes' }]) assert.equal((await POST(request(body))).status, 400);
  calls = [];
  global.fetch = async value => { calls.push(String(value)); return new Response(null, { status: 302, headers: { location: 'http://127.0.0.1/private' } }); };
  assert.equal((await POST(request({ url }))).status, 400); assert.equal(calls.length, 1, 'redirect target validated before following');
  calls = [];
  global.fetch = async value => { calls.push(String(value)); return calls.length === 1 ? new Response(null, { status: 301, headers: { location: '/canonical-post/' } }) : page(); };
  const redirect = await (await POST(request({ url }))).json();
  assert.equal(redirect.manualUrl, 'https://sikhizm.com/canonical-post/'); assert.equal(calls.length, 2);
  global.fetch = async () => new Response('image', { headers: { 'Content-Type': 'image/png' } });
  assert.equal((await POST(request({ url }))).status, 400);
  global.fetch = async () => new Response('big', { headers: { 'Content-Type': 'text/html', 'Content-Length': '2000001' } });
  assert.equal((await POST(request({ url }))).status, 400);
  global.fetch = async () => page('<p>No scripture here.</p>');
  assert.equal((await POST(request({ url }))).status, 400);
  const noMeaning = html.replace('Hukamnama Meaning in Gurmukhi', 'English Translation');
  calls = [];
  global.fetch = async value => { calls.push(String(value)); return page(noMeaning); };
  const missing = await (await POST(request({ url, translation: false }))).json();
  assert.equal(missing.translation, ''); assert.equal(missing.original, content.original); assert.equal(calls.length, 1);
  calls = [];
  global.fetch = async value => { calls.push(String(value)); if (String(value).includes('api.banidb.com')) throw new Error('Unavailable'); return page(noMeaning); };
  const unavailable = await (await POST(request({ url, translation: true }))).json();
  assert.equal(unavailable.translation, ''); assert.equal(unavailable.original, content.original);
  assert.equal(calls.length, 2, 'missing meaning may attempt exact BaniDB enrichment without changing source');
  calls = [];
  global.fetch = async value => {
    const target = String(value); calls.push(target);
    if (target.includes('/angs/')) return Response.json({ source: { sourceId: 'G', pageNo: 632 }, page: [{ verse: { unicode: content.original }, shabadId: 123 }] });
    if (target.includes('/shabads/')) return Response.json({ shabadInfo: { source: { sourceId: 'G' }, pageNo: 632 }, verses: [{ verse: { unicode: content.original }, translation: { pu: { ss: { unicode: content.translation } } } }] });
    return page(noMeaning);
  };
  const enriched = await (await POST(request({ url }))).json();
  assert.ok(enriched.translation.startsWith('ਹੇ ਮਨ!'));
  assert.equal(enriched.original, content.original); assert.equal(enriched.isToday, false);
  assert.equal(enriched.sourceDateISO, '2026-10-29'); assert.equal(enriched.manualUrl, url);
  assert.equal(calls.length, 3); assert.ok(enriched.sourceName.includes('BaniDB'));
  console.log('Manual Sikhizm URL import passed: old article, today’s editor date, native/excerpt fields, strict URL/redirect and size checks, missing meanings, unchanged daily validation and no automatic posting. No live posts.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { global.Date = realDate; global.fetch = realFetch; });
