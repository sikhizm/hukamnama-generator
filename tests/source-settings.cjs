const assert = require('node:assert/strict');
const fs = require('node:fs'), path = require('node:path'), ts = require('typescript');
for (const extension of ['.ts', '.tsx']) require.extensions[extension] = (module, filename) => {
  const source = fs.readFileSync(filename, 'utf8').replace(/(["'])@\/([^"']+)\1/g, (_, quote, file) => JSON.stringify(path.join(__dirname, '../src', file)));
  module._compile(ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText, filename);
};
const React = require('react');
const { create, act } = require('react-test-renderer');
global.IS_REACT_ACT_ENVIRONMENT = true;
const SourceSettings = require('../src/components/studio/SourceSettings.tsx').default;
const { DAILY_SOURCES, readSourceSelection } = require('../src/lib/hukamnama/sourceSelection.ts');
const { indiaClock } = require('../src/lib/morningPlan.ts');
const realFetch = fetch;
const record = { sourceDateISO: indiaClock().day, isToday: true, sourceName: 'Dekho Ji daily Hukamnama', ang: '654', original: 'ਬੇਦ ਪੁਰਾਨ', translation: 'ਅਰਥ', matchedAuthor: 'Bhagat Kabir Ji' };
const calls = [], applied = [];
let root, pending;
const inputs = () => root.root.findAllByType('input');
const radios = () => inputs().filter(input => input.props.type === 'radio');
const checks = () => inputs().filter(input => input.props.type === 'checkbox');
const fetchButton = () => root.root.findAllByType('button').find(node => String(node.children[0]).includes('selected sources'));
const importButton = () => root.root.findAllByType('button').find(node => String(node.children[0]).includes('Import Sikhizm') || node.children[0] === 'Fetching…');
(async () => {
  global.fetch = async url => { calls.push(String(url)); return new Response(JSON.stringify(record)); };
  await act(async () => { root = create(React.createElement(SourceSettings, { onUse: value => applied.push(value) })); });
  assert.equal(radios()[0].props.checked, true); assert.equal(checks().length, 0);
  assert.equal(calls.length, 0, 'opening settings never initiates a fetch');
  await act(async () => radios()[1].props.onChange());
  assert.equal(checks().length, 6);
  await act(async () => {
    for (const checkbox of checks().slice(0, 4)) checkbox.props.onChange({ target: { checked: false } });
    checks()[5].props.onChange({ target: { checked: false } });
  });
  await act(async () => fetchButton().props.onClick());
  let params = new URL('https://example.com' + calls[0]).searchParams;
  assert.equal(params.get('sources'), 'dekhoji'); assert.equal(params.get('translation'), '0'); assert.equal(params.get('refresh'), '1');
  assert.equal(applied.length, 1); assert.ok(root.root.findAllByProps({ role: 'status' })[0].children.join('').includes('Dekho Ji'));
  global.fetch = async () => new Response(JSON.stringify({ ...record, isToday: false, sourceDateISO: '2020-01-01' }));
  await act(async () => fetchButton().props.onClick());
  assert.equal(applied.length, 1, 'stale response never replaces editor');
  assert.ok(root.root.findAllByProps({ role: 'alert' }).length);
  global.fetch = async () => new Response(JSON.stringify({ error: 'Selected source unavailable' }), { status: 502 });
  await act(async () => fetchButton().props.onClick()); assert.equal(applied.length, 1);
  let count = 0;
  global.fetch = () => { count++; return new Promise(resolve => { pending = resolve; }); };
  await act(async () => { fetchButton().props.onClick(); fetchButton().props.onClick(); });
  assert.equal(count, 1, 'double-click cannot start parallel loads');
  assert.equal(fetchButton().props.disabled, true);
  await act(async () => pending(new Response(JSON.stringify(record))));
  assert.equal(applied.length, 2);
  await act(async () => checks()[4].props.onChange({ target: { checked: false } }));
  assert.equal(fetchButton().props.disabled, true);
  await act(async () => fetchButton().props.onClick()); assert.equal(count, 1);
  // URL import is independent of the selected daily sources and allows old posts.
  const urlInput = () => inputs().find(input => input.props.type === 'url');
  assert.equal(importButton().props.disabled, true);
  await act(async () => urlInput().props.onChange({ target: { value: 'https://sikhizm.com/old-evergreen/' } }));
  const manual = { ...record, isToday: false, manualUrl: 'https://sikhizm.com/old-evergreen/', sourceName: 'Sikhizm manual URL selection' };
  let requestOptions;
  global.fetch = async (url, options) => { calls.push(String(url)); requestOptions = options; return new Response(JSON.stringify(manual)); };
  await act(async () => importButton().props.onClick());
  assert.equal(calls.at(-1), '/api/hukamnama/sikhizm');
  assert.equal(requestOptions.method, 'POST');
  assert.deepEqual(JSON.parse(requestOptions.body), { url: manual.manualUrl, translation: false });
  assert.deepEqual(applied.at(-1), manual);
  assert.equal(applied.length, 3);
  assert.ok(root.root.findAllByProps({ role: 'status' })[0].children.join('').includes('does not verify'));
  global.fetch = async () => new Response(JSON.stringify({ error: 'Page unavailable' }), { status: 400 });
  await act(async () => importButton().props.onClick());
  assert.equal(applied.length, 3, 'failed URL import preserves editor');
  count = 0;
  global.fetch = () => { count++; return new Promise(resolve => { pending = resolve; }); };
  await act(async () => { importButton().props.onClick(); importButton().props.onClick(); });
  assert.equal(count, 1);
  assert.equal(fetchButton().props.disabled, true);
  await act(async () => pending(new Response(JSON.stringify(manual))));
  assert.equal(applied.length, 4);
  await act(async () => radios()[0].props.onChange());
  assert.equal(root.root.findAllByType('button').length, 0);
  assert.equal(readSourceSelection(new URLSearchParams('translation=0')), null, 'default mode ignores override-only translation option');
  assert.deepEqual(readSourceSelection(new URLSearchParams('sources=dekhoji,sikhizm')).sources, ['sikhizm', 'dekhoji']);
  assert.equal(DAILY_SOURCES.length, 5);
  await act(async () => root.unmount());
  console.log('Source settings passed: default mode, selected-only request, BaniDB off, stale/error preservation, empty selection and double-click guard. No publishing.');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => { global.fetch = realFetch; });
